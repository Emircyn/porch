// Writes public/brand-icons.svg: one <symbol> per platform, so pages reference icons with <use> instead of
// repeating long SVG paths in every link. Keep the ids in sync with src/lib/platforms.tsx.
import fs from "node:fs"
import * as icons from "simple-icons"

const ids = {
  instagram: "siInstagram", tiktok: "siTiktok", youtube: "siYoutube", x: "siX", threads: "siThreads",
  bluesky: "siBluesky", pinterest: "siPinterest", spotify: "siSpotify", soundcloud: "siSoundcloud",
  twitch: "siTwitch", github: "siGithub", etsy: "siEtsy", substack: "siSubstack", patreon: "siPatreon",
}

const symbols = Object.entries(ids).map(([id, name]) => {
  const icon = icons[name]
  if (!icon) throw new Error(`simple-icons has no ${name}`)
  return `<symbol id="${id}" viewBox="0 0 24 24"><path d="${icon.path}"/></symbol>`
})
fs.writeFileSync(
  "public/brand-icons.svg",
  `<svg xmlns="http://www.w3.org/2000/svg"><!-- Brand icons from simple-icons (CC0). Generated by scripts/build-brand-icons.mjs --><defs>${symbols.join("")}</defs></svg>\n`
)
console.log(`Wrote ${symbols.length} icons`)
