// Imports public-page themes from tweakcn's shadcn registry and writes:
//   src/app/page-themes.css  — shadcn CSS variables scoped to [data-page-theme="<id>"], light and dark
//   src/lib/themes.ts        — the theme list the app uses (ids, names, Pro flag)
// Usage: node scripts/import-page-themes.mjs [path-to-registry.json]
// After changing the list, update is_known_theme()/is_pro_theme() in a new migration.
import fs from "node:fs"

import { contrast, fixForeground, parseColor } from "./color-contrast.mjs"

const REGISTRY = "https://tweakcn.com/r/registry.json"

// Order is the order shown in the picker. Fonts map to the next/font variables in src/lib/page-fonts.ts and
// always end in a generic family, so text shows even before (or without) the web font.
const picks = [
  { id: "vercel", name: "Monochrome", pro: false, font: "var(--font-page-geist), ui-sans-serif, system-ui, sans-serif" },
  { id: "clean-slate", name: "Clean Slate", pro: false, font: "var(--font-page-inter), ui-sans-serif, system-ui, sans-serif" },
  { id: "caffeine", name: "Caffeine", pro: false, font: "ui-sans-serif, system-ui, sans-serif" },
  { id: "bubblegum", name: "Bubblegum", pro: true, font: "var(--font-page-poppins), ui-sans-serif, system-ui, sans-serif" },
  { id: "neo-brutalism", name: "Neo Brutalism", pro: true, font: "var(--font-page-dm-sans), ui-sans-serif, system-ui, sans-serif" },
  { id: "cyberpunk", name: "Cyberpunk", pro: true, font: "var(--font-page-outfit), ui-sans-serif, system-ui, sans-serif" },
  { id: "kodama-grove", name: "Kodama Grove", pro: true, font: "var(--font-page-merriweather), ui-serif, Georgia, serif" },
  { id: "sunset-horizon", name: "Sunset Horizon", pro: true, font: "var(--font-page-montserrat), ui-sans-serif, system-ui, sans-serif" },
  { id: "vintage-paper", name: "Vintage Paper", pro: true, font: "var(--font-page-libre-baskerville), ui-serif, Georgia, serif" },
  { id: "claymorphism", name: "Claymorphism", pro: true, font: "var(--font-page-plus-jakarta), ui-sans-serif, system-ui, sans-serif" },
  { id: "starry-night", name: "Starry Night", pro: true, font: "var(--font-page-libre-baskerville), ui-serif, Georgia, serif" },
]

const colorVars = [
  "background", "foreground", "card", "card-foreground", "popover", "popover-foreground",
  "primary", "primary-foreground", "secondary", "secondary-foreground", "muted", "muted-foreground",
  "accent", "accent-foreground", "border", "input", "ring",
]
const shadowVars = ["shadow-xs", "shadow-sm", "shadow-md", "shadow-lg"]

// WCAG AA for text (4.5:1). Many tweakcn themes fall short on button text or muted text, so the importer
// fixes them: buttons keep their text colour and darken or lighten the fill; muted text moves instead.
const AA = 4.5
const fixes = []

function ensureContrast(vars, id, mode) {
  const fixed = { ...vars }
  const note = (what, from, to) => fixes.push(`${id} (${mode}) ${what}: ${from} -> ${to}`)

  for (const [fg, bg] of [["foreground", "background"], ["card-foreground", "card"]]) {
    const next = fixForeground(fixed[fg], fixed[bg], AA)
    if (next) note(fg, fixed[fg], (fixed[fg] = next))
  }

  // Button text sits on --primary: move the fill, not the text, so the theme keeps its look.
  if (contrast(parseColor(fixed["primary-foreground"]), parseColor(fixed.primary)) < AA) {
    const next = fixForeground(fixed.primary, fixed["primary-foreground"], AA)
    note("primary", fixed.primary, (fixed.primary = next))
  }

  // Muted text has to work on both the page and on cards; fix against whichever is worse.
  const worst = [fixed.background, fixed.card].sort(
    (a, b) => contrast(parseColor(fixed["muted-foreground"]), parseColor(a)) -
      contrast(parseColor(fixed["muted-foreground"]), parseColor(b))
  )[0]
  const muted = fixForeground(fixed["muted-foreground"], worst, AA)
  if (muted) note("muted-foreground", fixed["muted-foreground"], (fixed["muted-foreground"] = muted))
  return fixed
}

const source = process.argv[2]
const registry = source
  ? JSON.parse(fs.readFileSync(source, "utf8"))
  : await (await fetch(REGISTRY)).json()
const items = registry.items ?? registry

function block(selector, vars, pick) {
  const lines = colorVars.map((name) => `  --${name}: ${vars[name]};`)
  lines.push(`  --radius: ${vars.radius ?? "0.5rem"};`)
  lines.push(`  --font-sans: ${pick.font};`)
  lines.push(`  --page-tracking: ${vars["tracking-normal"] ?? vars["letter-spacing"] ?? "0em"};`)
  for (const name of shadowVars) {
    if (vars[name]) lines.push(`  --page-${name}: ${vars[name]};`)
  }
  return `${selector} {\n${lines.join("\n")}\n}`
}

const css = [
  "/* Generated by scripts/import-page-themes.mjs from tweakcn (https://tweakcn.com). Do not edit by hand. */",
]
for (const pick of picks) {
  const item = items.find((entry) => entry.name === pick.id)
  if (!item) throw new Error(`Theme ${pick.id} is not in the registry`)
  const shared = item.cssVars.theme ?? {}
  const light = { ...shared, ...item.cssVars.light }
  const dark = { ...shared, ...light, ...item.cssVars.dark }
  for (const name of colorVars) {
    if (!light[name] || !dark[name]) throw new Error(`${pick.id} is missing --${name}`)
  }
  const safeLight = ensureContrast(light, pick.id, "light")
  const safeDark = ensureContrast(dark, pick.id, "dark")
  // Site previews follow the site's .dark class; public pages (data-color-mode="auto") follow the visitor's
  // system setting with no JavaScript at all.
  css.push(block(`[data-page-theme="${pick.id}"]`, safeLight, pick))
  css.push(block(`.dark [data-page-theme="${pick.id}"]`, safeDark, pick))
  css.push(
    `@media (prefers-color-scheme: dark) {\n${block(`[data-page-theme="${pick.id}"][data-color-mode="auto"]`, safeDark, pick)
      .split("\n")
      .map((line) => `  ${line}`)
      .join("\n")}\n}`
  )
}
fs.writeFileSync("src/app/page-themes.css", css.join("\n\n") + "\n")

const ts = `// Generated by scripts/import-page-themes.mjs. Do not edit by hand; change the list in the script.
// Colours, fonts, radius and shadows live in src/app/page-themes.css under [data-page-theme].

export type PageTheme = {
  id: ThemeId
  name: string
  pro: boolean
}

export const themes = ${JSON.stringify(
  picks.map(({ id, name, pro }) => ({ id, name, pro })),
  null,
  2
).replace(/"(\w+)":/g, "$1:")} as const

export type ThemeId = (typeof themes)[number]["id"]

export const defaultThemeId: ThemeId = "${picks[0].id}"

export function getTheme(id: string | null | undefined): PageTheme {
  return themes.find((theme) => theme.id === id) ?? themes[0]
}
`
fs.writeFileSync("src/lib/themes.ts", ts)
console.log(`Wrote ${picks.length} themes`)
console.log(fixes.length ? `Contrast fixes (WCAG AA):\n  ${fixes.join("\n  ")}` : "All themes pass WCAG AA")
